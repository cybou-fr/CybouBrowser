#!/usr/bin/env python3
"""Engineering report on the proposed not_applicable OWASP rows, generated from the repository data.
Python 3.10+, standard library only.

  python tools/security/na_report.py            # write docs/NA_REPORT.md
  python tools/security/na_report.py --check    # exit 1 if facts fail or the report is stale

Each N/A category in tests/security/na-categories.json rests on architecture facts; every fact is a pattern the
product sources must not contain, checked here and by owasp_gate.py --mode framework. A broken fact reopens the
category instead of leaving a stale justification in place.
"""
import argparse
import json
from pathlib import Path
import re
import subprocess
import sys

ROOT=Path(__file__).resolve().parents[2]
CATEGORIES=ROOT/"tests/security/na-categories.json"
COVERAGE=ROOT/"tests/security/coverage.json"
CASES=ROOT/"tests/security/cases.json"
REPORT=ROOT/"docs/NA_REPORT.md"

def read(path):
    return json.loads(Path(path).read_text(encoding="utf-8"))

def product_files(spec):
    try:
        listed=subprocess.run(["git","ls-files",*spec["include"]],cwd=ROOT,text=True,capture_output=True,check=True).stdout.split()
    except (OSError,subprocess.SubprocessError):
        listed=[p.relative_to(ROOT).as_posix() for inc in spec["include"] for p in (ROOT/inc).rglob("*") if p.is_file()]
    skip=re.compile(spec["excludeRegex"])
    return sorted(f for f in listed if not skip.search(f) and (ROOT/f).is_file())

def check_facts(data):
    """fact id -> list of 'file:line' places where the forbidden pattern occurs in product sources."""
    files={f:(ROOT/f).read_text(encoding="utf-8",errors="replace").splitlines() for f in product_files(data["productSources"])}
    hits={}
    for fid,fact in data["facts"].items():
        rx=re.compile(fact["forbid"])
        hits[fid]=[f"{f}:{n}" for f,lines in files.items() for n,line in enumerate(lines,1) if rx.search(line)]
    return hits,len(files)

def validate(data, rows, cases):
    """Structural errors: unmapped rows, unknown facts, cases or architecture files."""
    errors=[]
    by_reason={c["proposalRationale"]:c for c in data["categories"]}
    if len(by_reason)!=len(data["categories"]): errors.append("na-categories: duplicate proposalRationale")
    for r in rows:
        if r.get("disposition")!="applicable" and r.get("proposedDisposition")=="not_applicable" and r.get("proposalRationale") not in by_reason:
            errors.append(r["id"]+": N/A proposal has no category in na-categories.json")
    for c in data["categories"]:
        errors+=[f"{c['id']}: unknown fact {f}" for f in c["facts"] if f not in data["facts"]]
        errors+=[f"{c['id']}: unknown case {k}" for k in c["equivalentCases"] if k not in cases]
        errors+=[f"{c['id']}: architecture file missing: {a}" for a in c["architecture"] if not (ROOT/a).is_file()]
        if not c.get("reason") or not c.get("revisit"): errors.append(c["id"]+": needs reason and revisit")
    return errors

def short(text, n=110):
    text=" ".join(str(text).split()).replace("|","/")
    return text if len(text)<=n else text[:n-1].rstrip()+"…"

def render(data, rows, cases, hits, scanned):
    proposed=[r for r in rows if r.get("disposition")!="applicable" and r.get("proposedDisposition")=="not_applicable"]
    by_cat={c["id"]:[r for r in proposed if r.get("proposalRationale")==c["proposalRationale"]] for c in data["categories"]}
    broken={f for f,h in hits.items() if h}
    out=["# Proposed not-applicable OWASP requirements: engineering report","",
         "*Generated by `tools/security/na_report.py` from `tests/security/coverage.json` and `tests/security/na-categories.json`; do not edit by hand.*","",
         f"Of the {len(rows)} pinned OWASP ASVS 5.0.0 and WSTG 4.2 requirements, **{len(proposed)}** are proposed as not applicable to CYBOU, a desktop browser that serves nothing, holds no accounts and has no back end. "
         "This report gives the ground for each proposal, the architecture it rests on, the browser risks that are still tested in its place, and when it must be reconsidered.","",
         "It is an engineering report, not an approval. The rows stay `untriaged` proposals; item-by-item review by a named reviewer is a 1.0.0-rc gate ([VERSIONING](VERSIONING.md)).","",
         "## How the grounds are kept honest","",
         f"Each category names **architecture facts**: patterns the product sources must not contain. The facts are checked against {scanned} product files under `src/` and `qml/` "
         "(test fixtures and diagnostic probes excluded, since they are built only into `cybou_tests`). `owasp_gate.py --mode framework` runs the same check, so a change that breaks a fact fails the gate and reopens every category resting on it.","",
         "| Fact | Claim | Status |","| --- | --- | --- |"]
    for fid,fact in data["facts"].items():
        status="holds" if not hits[fid] else "**broken**: "+", ".join(hits[fid][:3])
        out.append(f"| `{fid}` | {fact['claim']} | {status} |")
    out+=["","## Summary","","| Category | Rows | Facts | Still tested through |","| --- | --- | --- | --- |"]
    for c in data["categories"]:
        state="**reopened**" if set(c["facts"])&broken else "hold"
        out.append(f"| [{c['title']}](#{c['id']}) | {len(by_cat[c['id']])} | {state} | {', '.join(c['equivalentCases'])} |")
    out.append(f"| **Total** | **{sum(map(len,by_cat.values()))}** | | |")
    for c in data["categories"]:
        out+=["",f'<a id="{c["id"]}"></a>',"",f"## {c['title']} ({len(by_cat[c['id']])})","",c["reason"],"",
              "**Rests on:** "+"; ".join(f"`{f}` ({'holds' if f not in broken else 'broken'})" for f in c["facts"]),"",
              "**Architecture:** "+", ".join(f"[{Path(a).name}](../{a})" for a in c["architecture"]),"",
              "**Browser risks still tested:** "+"; ".join(f"{k} ({short(cases[k].get('objective',''),70)})" for k in c["equivalentCases"]),"",
              "**Reconsider when:** "+c["revisit"],"",
              "| Requirement | Title | Note |","| --- | --- | --- |"]
        for r in by_cat[c["id"]]:
            out.append(f"| {r['id']} | {short(r.get('title',''))} | {short(r.get('proposalNote',''),90)} |")
    return "\n".join(out)+"\n"

def build():
    data,rows=read(CATEGORIES),read(COVERAGE)["requirements"]
    cases={c["id"]:c for c in read(CASES)["cases"]}
    hits,scanned=check_facts(data)
    errors=validate(data,rows,cases)+[f"N/A fact broken: {f} at {', '.join(h[:3])}" for f,h in hits.items() if h]
    return render(data,rows,cases,hits,scanned),errors

def main():
    p=argparse.ArgumentParser(description=__doc__,formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--check",action="store_true",help="fail on broken facts or a stale report instead of writing")
    a=p.parse_args()
    text,errors=build()
    if a.check:
        if not REPORT.is_file() or REPORT.read_text(encoding="utf-8")!=text: errors.append("docs/NA_REPORT.md is stale: run tools/security/na_report.py")
    else:
        REPORT.write_text(text,encoding="utf-8",newline="\n")
        print("NA_REPORT.md written")
    for e in errors: print(" -",e,file=sys.stderr)
    return 1 if errors else 0

if __name__=="__main__":
    sys.exit(main())
